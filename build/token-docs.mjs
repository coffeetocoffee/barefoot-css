/* Barefoot — regenerate the token reference in docs/theming.md from
   src/tokens.css. Parses the :root block of the tokens layer: every
   `/* ---- Section ---- * /` header opens a table group, every custom
   property becomes a row, and its same-line trailing comment becomes
   the Purpose column. Replaces the block between <!-- TOKENS:START -->
   and <!-- TOKENS:END -->. Idempotent — safe to run on every build.

   The parity test in tests/css.spec.js fails when a token lands in
   tokens.css without this script being re-run.

   Usage: npm run docs:tokens */
import { readFileSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { checkContrast } from "./contrast.mjs";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const TOKENS = join(root, "src", "tokens.css");
const THEMING = join(root, "docs", "theming.md");
const START = "<!-- TOKENS:START -->";
const END = "<!-- TOKENS:END -->";

const SECTION = /^\s*\/\*\s*-+\s*(.+?)\s*-+\s*(?:\*\/)?\s*$/;
const CUSTOM_PROP = /^\s*(--bf-[a-z0-9-]+):/;

function parseGroups(source) {
  const rootStart = source.indexOf(":root {");
  if (rootStart === -1) throw new Error("src/tokens.css has no :root block");
  const body = source.slice(rootStart);

  const groups = [];
  let current = null;
  let buffer = "";
  let inHeader = false;
  const seen = new Set();

  for (const line of body.split("\n")) {
    // Multi-line `/* ---- Title ----` headers keep their description
    // prose on the following lines — consume it, don't parse it.
    if (inHeader) {
      if (line.includes("*/")) inHeader = false;
      continue;
    }
    // A logical declaration may wrap; accumulate until the semicolon.
    if (buffer || CUSTOM_PROP.test(line)) {
      buffer += ` ${line.trim()}`;
      if (!buffer.includes(";")) continue;
      const decl = buffer;
      buffer = "";
      const [, name] = decl.match(CUSTOM_PROP);
      // First declaration of a name wins — the @supports oklch block
      // re-declares the Chroma tokens; their color-mix fallbacks above
      // are the documented defaults.
      if (!current || seen.has(name)) continue;
      seen.add(name);
      const value = decl
        .slice(decl.indexOf(":") + 1, decl.indexOf(";"))
        .replace(/\s+/g, " ")
        .trim();
      const purpose = decl.match(/;\s*\/\*\s*(.*?)\s*\*\//)?.[1] ?? "";
      current.rows.push({ name, value, purpose });
      continue;
    }
    const header = line.match(SECTION);
    if (header) {
      if (!line.includes("*/")) inHeader = true;
      current = { title: header[1], rows: [] };
      groups.push(current);
    }
  }
  return groups.filter((g) => g.rows.length > 0);
}

function renderTable({ title, rows }) {
  const lines = [
    `### ${title}`,
    "",
    "| Token | Default | Purpose |",
    "|---|---|---|",
    ...rows.map(
      ({ name, value, purpose }) =>
        `| \`${name}\` | \`${value}\` | ${purpose} |`
    ),
  ];
  return lines.join("\n");
}

const groups = parseGroups(readFileSync(TOKENS, "utf8"));
if (groups.length === 0) {
  console.error("No --bf-* declarations parsed from src/tokens.css.");
  process.exit(1);
}

const generated = [
  START,
  "<!-- Generated by build/token-docs.mjs from src/tokens.css.",
  "     Do not edit inside this region — change the token (its",
  "     trailing comment is the Purpose column) and re-run",
  "     npm run docs:tokens. -->",
  "",
  ...groups.map((g) => renderTable(g) + "\n"),
  END,
].join("\n");

const theming = readFileSync(THEMING, "utf8");
const startIdx = theming.indexOf(START);
const endIdx = theming.indexOf(END);
if (startIdx === -1 || endIdx === -1 || endIdx < startIdx) {
  console.error("docs/theming.md is missing the TOKENS markers — add them:");
  console.error(`  ${START}\n  ...\n  ${END}`);
  process.exit(1);
}

writeFileSync(
  THEMING,
  theming.slice(0, startIdx) + generated + theming.slice(endIdx + END.length)
);
console.log(
  `theming.md token tables regenerated (${groups.length} sections, ` +
    `${groups.reduce((n, g) => n + g.rows.length, 0)} tokens).`
);

// Chroma contrast guard — warn at doc-gen time; hard fail lives in size.mjs
const { warnings } = checkContrast({ strict: false });
if (warnings.length > 0) {
  console.warn(`\ncontrast: ${warnings.length} pair(s) below AA — see warnings above. Suggested fix: oklch(from var(--bf-primary) calc((0.7 - l) * 100) 0 0)`);
}
